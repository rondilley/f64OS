( f64 BASIC V2 - bmain.f: errors, the READY loop and the BASIC word )
DECIMAL

: ERRMSG-SRC ( -- addr len )
    S" TOO MANY FILES|FILE OPEN|FILE NOT OPEN|FILE NOT FOUND|DEVICE NOT PRESENT|NOT INPUT FILE|NOT OUTPUT FILE|MISSING FILE NAME|ILLEGAL DEVICE NUMBER|NEXT WITHOUT FOR|SYNTAX|RETURN WITHOUT GOSUB|OUT OF DATA|ILLEGAL QUANTITY|OVERFLOW|OUT OF MEMORY|UNDEF'D STATEMENT|BAD SUBSCRIPT|REDIM'D ARRAY|DIVISION BY ZERO|ILLEGAL DIRECT|TYPE MISMATCH|STRING TOO LONG|FILE DATA|FORMULA TOO COMPLEX|CAN'T CONTINUE|UNDEF'D FUNCTION|VERIFY|LOAD|BREAK"
;
( Text of error n, 1..30 )
: ERRMSG ( n -- addr len )
    >R ERRMSG-SRC
    R> 1- ?DUP IF 0 DO 2DUP 124 SCAN-CHAR 1+ /STRING LOOP THEN
    2DUP 124 SCAN-CHAR DUP 0< IF DROP ELSE NIP THEN
;
: READY ( -- ) S" READY." PTYPE 13 CHROUT ;
: PRINT-IN ( -- ) CURLINE 65535 <> IF S"  IN " PTYPE CURLINE PNUM THEN ;
: SAVE-CONT ( -- ) CURLINE 65535 <> IF TXTPTR TO CONT-TXT CURLINE TO CONT-LINE THEN ;
( Show an error, as the C64 does: ?SYNTAX  ERROR IN 10 )
: SHOW-ERROR ( n -- )
    0 TO OUTCH 0 TO IN-MODE
    DIRECT? IF 65535 TO CURLINE THEN
    DUP E-END = IF DROP SAVE-CONT EXIT THEN
    CX IF 13 CHROUT THEN
    DUP E-BREAK = IF DROP S" BREAK" PTYPE PRINT-IN 13 CHROUT SAVE-CONT EXIT THEN
    0 TO CONT-TXT
    63 CHROUT
    DUP 1 30 WITHIN IF ERRMSG PTYPE ELSE DROP S" INTERNAL" PTYPE THEN
    S"   ERROR" PTYPE PRINT-IN 13 CHROUT
;

( ---- Direct mode ---- )
260 ALLOT CONSTANT DIRBUF
: EXEC-DIRECT ( -- )
    58 DIRBUF C! TBUF DIRBUF 1+ TB-LEN CMOVE
    DIRBUF TO TXTPTR 65535 TO CURLINE
    RUN-LOOP
;
( A line that starts with a number goes into the program )
: ENTER-LINE ( addr len -- )
    0 >R
    BEGIN
        DUP 0> IF OVER C@ DIGIT? ELSE 0 THEN
    WHILE
        R> 10 * 2 PICK C@ 48 - + >R 1 /STRING
        R@ 63999 > IF RDROP 2DROP SYNERR THEN
    REPEAT
    SKIPSP CRUNCH R> STORE-LINE
    CLEAR-ALL 0 TO CONT-TXT
;
: BYE? ( addr len -- flag )
    3 = IF DUP C@ 66 = OVER 1+ C@ 89 = AND SWAP 2 + C@ 69 = AND ELSE DROP 0 THEN
;
0 VALUE B-QUIT
: B-STEP ( -- )
    0 TO IN-MODE
    READ-LINE SKIPSP
    DUP 0= IF 2DROP EXIT THEN
    2DUP BYE? IF 2DROP 1 TO B-QUIT EXIT THEN
    OVER C@ DIGIT? IF ENTER-LINE EXIT THEN
    CRUNCH EXEC-DIRECT READY
;

( ---- Cold start ---- )
: MEM-INIT ( -- )
    MEM 65536 0 FILL
    47 0 M!  55 1 M!
    14 646 M!  4 648 M!
    14 53280 M!  6 53281 M!  21 53272 M!  151 56576 M!
    2049 43 MW!  40960 55 MW!
    MEM 1024 + 1000 32 FILL
    MEM 55296 + 1000 14 FILL
;
: BANNER ( -- )
    147 CHROUT 13 CHROUT
    S"     **** F64OS BASIC V2 ****" PTYPE 13 CHROUT 13 CHROUT
    S"  64K RAM SYSTEM  38911 BASIC BYTES FREE" PTYPE 13 CHROUT 13 CHROUT
;
: COLD-START ( -- )
    MEM-INIT
    0 TO CX 0 TO CY 0 TO RVS 0 TO QUOTE LINK 25 0 FILL
    VIC-UPDATE GFX-ON IF 53280 M@ SET-BORDER THEN
    NEW-PROG CLEAR-ALL 0 TO CONT-TXT 0 TO TI-OFFSET
    BANNER READY
;
: B-REPL ( -- )
    0 TO B-QUIT
    BEGIN
        ['] B-STEP CATCH
        ?DUP IF
            DUP E-RESET = IF DROP COLD-START ELSE SHOW-ERROR READY THEN
        THEN
        B-QUIT
    UNTIL
;
0 VALUE B-STARTED
( Start BASIC. Type BYE to go back to Forth. The program stays in memory. )
: BASIC ( -- )
    FINIT
    B-STARTED 0= IF MEM-INIT THEN
    GFX-ENTER
    B-STARTED 0= IF COLD-START 1 TO B-STARTED ELSE READY THEN
    B-REPL
    GFX-EXIT
    ." Back in Forth. Type BASIC to go back to BASIC." CR
;
( Remove all BASIC words from the dictionary )
: BASIC-UNLOAD ( -- ) GFX-EXIT B-ORIG-LATEST LATEST ! B-ORIG-HERE HERE ! ;

." f64 BASIC V2 is loaded. Type BASIC to start it." CR
