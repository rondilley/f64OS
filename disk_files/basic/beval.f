0 VALUE ETYPE                  ( type of the last value: 0 number, 1 string )
0 VALUE EDEPTH
: TYPE-NUM ( -- ) ETYPE IF E-TYPE THROW THEN ;
: TYPE-STR ( -- ) ETYPE 0= IF E-TYPE THROW THEN ;
: EVAL-NUM ( -- f ) EVAL TYPE-NUM ;
: EVAL-STR ( -- addr len ) EVAL TYPE-STR ;
